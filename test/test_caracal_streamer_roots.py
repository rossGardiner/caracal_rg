"""CARACAL root selection must work for a session or its parent."""

import importlib
import os
import sys
from pathlib import Path
from hashlib import sha256
from types import ModuleType, SimpleNamespace

import pytest


@pytest.fixture
def streamer_type(monkeypatch):
    # Avoid requiring caracal-python's optional scientific/GPS dependencies for
    # directory-discovery and packet-path tests.
    caracal = ModuleType("caracal")

    class FakeParser:
        def __init__(self, syslog_file):
            self.syslog_file = syslog_file

        def process(self):
            header = SimpleNamespace(
                sysDuration=6.0,
                stats=SimpleNamespace(
                    num_files=2,
                    median_GPS_lat=1.0,
                    median_GPS_lon=2.0,
                ),
                headerID=SimpleNamespace(deviceID="test-device", cardID="test-card"),
            )
            session = SimpleNamespace(
                path="not-a-real-folder",  # Should not be used for audio paths.
                header=header,
                audioFiles=[
                    SimpleNamespace(subpath="aud1700000000/file_1700000000.wav"),
                    SimpleNamespace(subpath="aud1700000000/file_1700000003.wav"),
                ],
            )
            return SimpleNamespace(sessions=[session])

    caracal.SyslogParser = FakeParser
    monkeypatch.setitem(sys.modules, "caracal", caracal)
    monkeypatch.delitem(sys.modules, "src.CaracalStreamer", raising=False)
    streamer_class = importlib.import_module("src.CaracalStreamer").CaracalStreamer
    yield streamer_class
    sys.modules.pop("src.CaracalStreamer", None)


def make_session(parent: Path, name: str, with_syslog: bool = True) -> Path:
    folder = parent / name
    folder.mkdir(parents=True)
    audio = folder / "aud1700000000"
    audio.mkdir()
    for filename in ("file_1700000000.wav", "file_1700000003.wav"):
        (audio / filename).write_bytes(b"test file")
    if with_syslog:
        (folder / "syslog.txt").write_text("SYS,0,1,Start\n")
    return folder


def test_single_and_multi_session_roots_resolve_same_audio_and_cache_id(
    streamer_type, tmp_path
):
    first = make_session(tmp_path, "24.A")
    make_session(tmp_path, "23.A")
    parent_streamer = streamer_type(str(tmp_path))
    single_streamer = streamer_type(str(first))

    from_parent = {
        Path(packet.misc_metadata["syslog_file"]).parent.name: packet
        for packet in parent_streamer.get_audio_packets()
    }["24.A"]
    from_single = single_streamer.get_audio_packets()[0]

    assert from_parent.audio_paths == from_single.audio_paths
    assert from_single.recording_id == from_parent.recording_id
    # Preserve the IDs generated by the original parent-root implementation.
    expected_identity = "\n".join(
        os.path.relpath(path, tmp_path) for path in from_parent.audio_paths
    )
    assert from_parent.recording_id == sha256(expected_identity.encode()).hexdigest()
    assert all(Path(path).is_file() for path in from_single.audio_paths)
    assert len(parent_streamer.syslog_files) == 2
    assert len(single_streamer.syslog_files) == 1


def test_relative_session_directory_does_not_duplicate_audio_path(
    streamer_type, tmp_path, monkeypatch
):
    session = make_session(tmp_path, "24.A")
    monkeypatch.chdir(tmp_path)
    streamer = streamer_type("24.A")
    packet = streamer.get_audio_packets()[0]
    assert packet.audio_paths[0] == os.path.join(
        "24.A", "aud1700000000", "file_1700000000.wav"
    )
    assert all(Path(path).is_file() for path in packet.audio_paths)


def test_missing_syslogs_warn_and_continue_without_noisy_unrelated_folders(
    streamer_type, tmp_path, capsys
):
    make_session(tmp_path, "23.A")
    make_session(tmp_path, "24.A", with_syslog=False)
    (tmp_path / "$RECYCLE.BIN").mkdir()
    (tmp_path / "Seagate").mkdir()
    (tmp_path / "unrelated" / "other").mkdir(parents=True)

    streamer = streamer_type(str(tmp_path))
    assert len(streamer.syslog_files) == 1
    # Only recording-like folders with audNNN subdirectories count as missing.
    assert streamer.missing_syslogs == ["24.A"]
    assert "24.A" in capsys.readouterr().out
    assert len(streamer.get_audio_packets()) == 1


def test_all_missing_syslogs_report_clear_error(streamer_type, tmp_path):
    session = make_session(tmp_path, "24.A", with_syslog=False)
    with pytest.raises(ValueError, match="No syslog.txt found"):
        streamer_type(str(tmp_path))
    with pytest.raises(ValueError, match="No syslog.txt found"):
        streamer_type(str(session))


def test_unrelated_dirs_are_ignored_and_nested_logs_not_searched(
    streamer_type, tmp_path
):
    (tmp_path / "$RECYCLE.BIN").mkdir()
    (tmp_path / "nested" / "deep").mkdir(parents=True)
    (tmp_path / "nested" / "deep" / "syslog.txt").write_text("test")
    logs, missing = streamer_type.discover_syslogs(str(tmp_path))
    assert logs == []
    assert missing == []


def test_unknown_root_fails_with_readable_path(streamer_type, tmp_path):
    with pytest.raises(ValueError, match="directory does not exist"):
        streamer_type(str(tmp_path / "not-here"))
